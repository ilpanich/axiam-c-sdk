def paginated_models() -> list[str]:
    """Response schemas returned as a page -- each gets a typed page struct."""
    out: set[str] = set()
    for ns in REGISTRY["namespaces"].values():
        for op in ns["operations"].values():
            if op["response"]["kind"] == "page" and op["response"]["schema"]:
                out.add(pascal(op["response"]["schema"].lstrip("[]")))
    return sorted(out)


def array_models() -> list[str]:
    """Response schemas returned as a BARE ARRAY (27.4 rule 4: never a page)."""
    out: set[str] = set()
    for ns in REGISTRY["namespaces"].values():
        for op in ns["operations"].values():
            if op["response"]["kind"] == "array" and op["response"]["schema"]:
                out.add(pascal(op["response"]["schema"].lstrip("[]")))
    return sorted(out)


def emit_models_header() -> str:
    """The generated model structs, enums, page/list wrappers and free declarations."""
    secrets = sensitive_map()
    out = [BANNER_C]
    out.append("")
    out.append("#ifndef AXIAM_MANAGEMENT_MODELS_H")
    out.append("#define AXIAM_MANAGEMENT_MODELS_H")
    out.append("")
    out.append("#include <stddef.h>")
    out.append("")
    out.append('#include "axiam/management.h"')
    out.append('#include "axiam/sensitive.h"')
    out.append("")
    out.extend(comment(
        "A free-form JSON member (`metadata`, `attribute_map`) is raw JSON TEXT, not a "
        "parsed tree. Every other public header in this SDK keeps the bundled cJSON "
        "internal, and exposing it here would put a third-party type in the installed "
        "ABI -- forcing cJSON onto every consumer's include path to name a field they "
        "will hand to their own parser anyway."))
    out.append("")
    out.append("#ifdef __cplusplus")
    out.append('extern "C" {')
    out.append("#endif")
    out.append("")

    # ---- enums ----
    for name in schema_closure():
        rendered = pascal(name)
        if rendered not in ENUMS:
            continue
        schema = SCHEMAS.get(name) or {}
        values = [str(v) for v in (schema.get("enum") or [])]
        if not values:
            continue
        out.extend(doc(schema.get("description")
                       or f"The `{rendered}` enumeration from the server's OpenAPI document."))
        if any(enum_const(rendered, v) == enum_const(rendered, "unknown") for v in values):
            raise SystemExit(
                f"enum {rendered}: the spec declares a value whose constant collides with "
                "the open-enum carrier this generator appends."
            )
        out.append(f"typedef enum axiam_mgmt_{snake(rendered)} {{")
        out.append(f"    {enum_const(rendered, values[0])} = 0, /**< Wire value `{values[0]}`. */")
        for value in values[1:]:
            out.append(f"    {enum_const(rendered, value)}, /**< Wire value `{value}`. */")
        out.append(f"    {enum_const(rendered, 'unknown')}, "
                   "/**< A value this SDK's copy of the spec does not list. */")
        out.append(f"}} axiam_mgmt_{snake(rendered)}_t;")
        out.append("")
        out.extend(doc(
            f"Parse a wire value into an {rendered}.\n\n"
            f"Returns 0 and yields `{enum_const(rendered, 'unknown')}` for a value this "
            "SDK's copy of the spec does not list, rather than reporting a failure the "
            "caller would have to fail the whole record over (CONTRACT.md \u00a727.11 rule 1). "
            "Returns -1 only for a NULL argument.\n\n"
            "It is never mapped to one of the KNOWN constants, which is the trap this used "
            "to avoid by failing: reading a new state as whichever constant happens to be "
            "first turns a new server state into a wrong one, and on this surface these "
            "values gate access. The unknown constant is appended LAST, so it is never the "
            "zero value a calloc'd struct starts at either."))
        out.append(f"int axiam_mgmt_{snake(rendered)}_from_wire(const char *value, "
                   f"axiam_mgmt_{snake(rendered)}_t *out);")
        out.append("")
        out.extend(doc(
            f"The wire spelling of an {rendered}. Never NULL.\n\n"
            f"`{enum_const(rendered, 'unknown')}` spells as the empty string, which no "
            "server value is: carrying an unrecognised value back into an update is refused "
            "by the server rather than written as a spelling it never used."))
        out.append(f"const char *axiam_mgmt_{snake(rendered)}_to_wire("
                   f"axiam_mgmt_{snake(rendered)}_t value);")
        out.append("")

    # ---- forward declarations, so models may reference each other in any order ----
    structs = [pascal(n) for n in schema_closure()
               if pascal(n) not in ENUMS and (flatten(n)[0] or discriminated(SCHEMAS.get(n) or {}))]
    out.extend(comment(
        "Forward declarations. The spec's types reference each other freely and in both "
        "directions, so every struct is named before any is defined."))
    for name in structs:
        out.append(f"typedef struct axiam_mgmt_{snake(name)} {model_type(name)};")
    out.append("")

    # ---- structs ----
    for name in schema_closure():
        rendered = pascal(name)
        if rendered in ENUMS:
            continue
        fields, description = fields_of(name, secrets.get(name, set()))
        if not fields:
            continue

        summary = escape(description) if description else \
            f"The `{rendered}` schema from the server's OpenAPI document."
        sparse = all(not f["required"] for f in fields)
        if sparse:
            summary += (
                "\n\nEvery member is optional, so this is a SPARSE body (27.4 rule 5): a "
                "NULL pointer -- or a `has_` flag left 0 -- means the field is OMITTED "
                "from the request entirely, not sent as null. On a sparse update those "
                "say opposite things, and only omission means \"leave it alone\".")
        out.extend(doc(summary))
        out.append(f"struct axiam_mgmt_{snake(rendered)} {{")
        for f in fields:
            out.extend(doc(field_doc(f) + ("" if f["required"] else " Optional."), "    "))
            if f["kind"] in {"string_array", "model_array"}:
                out.append(f"    {f['decl']}{f['name']};")
                out.append(f"    size_t {f['name']}_count; /**< Entries in `{f['name']}`. */")
            else:
                out.append(f"    {f['decl']}{f['name']};")
            if scalar(f["kind"]) and not f["required"]:
                out.append(f"    int has_{f['name']}; /**< 1 when `{f['name']}` is set. */")
        out.append("};")
        out.append("")
        out.extend(doc(
            f"Free a {rendered} and everything it owns. Safe to pass NULL.\n\n"
            "Frees the struct itself as well as its members, so it pairs with whatever "
            "allocated it and there is never a question of which half you own."))
        out.append(f"void {model_prefix(rendered)}_free({model_type(rendered)} *value);")
        out.append("")

    # ---- page and list wrappers ----
    for name in paginated_models():
        out.extend(doc(
            f"One page of {name} objects (27.4 rule 4).\n\n"
            "`total` is the SERVER's count across every page. It is NOT `count`, and "
            "deriving one from the other is how a management tool silently processes the "
            "first fifty of four hundred rows -- so they are separate members and neither "
            "is computed from the other."))
        out.append(f"typedef struct axiam_mgmt_{snake(name)}_page {{")
        out.append(f"    {model_type(name)} **items; /**< The items on THIS page. */")
        out.append("    size_t count;              /**< How many items are on this page. */")
        out.append("    long total;                /**< The server's total across all pages. */")
        out.append("    axiam_mgmt_page_req_t request; /**< The request that produced this page. */")
        out.append(f"}} axiam_mgmt_{snake(name)}_page_t;")
        out.append("")
        out.extend(doc(f"Free a page of {name} objects and every item in it. Safe to pass NULL."))
        out.append(f"void axiam_mgmt_{snake(name)}_page_free(axiam_mgmt_{snake(name)}_page_t *page);")
        out.append("")

    for name in array_models():
        out.extend(doc(
            f"A plain list of {name} objects.\n\n"
            "This is what a BARE-ARRAY endpoint returns. 27.4 rule 4 is explicit that "
            "such a response MUST NOT be modelled as a page: there is no `total`, no "
            "offset and no next page, and dressing it as one would invite a caller to "
            "walk something that has already ended."))
        out.append(f"typedef struct axiam_mgmt_{snake(name)}_list {{")
        out.append(f"    {model_type(name)} **items; /**< Every item the server returned. */")
        out.append("    size_t count;              /**< How many. */")
        out.append(f"}} axiam_mgmt_{snake(name)}_list_t;")
        out.append("")
        out.extend(doc(f"Free a list of {name} objects and every item in it. Safe to pass NULL."))
        out.append(f"void axiam_mgmt_{snake(name)}_list_free(axiam_mgmt_{snake(name)}_list_t *list);")
        out.append("")

    out.append("#ifdef __cplusplus")
    out.append("}")
    out.append("#endif")
    out.append("")
    out.append("#endif /* AXIAM_MANAGEMENT_MODELS_H */")
    return "\n".join(out) + "\n"


