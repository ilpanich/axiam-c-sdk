        for opname, op in nsdef["operations"].items():
            count += 1
            params = op_params(namespace, op)
            body = example_response(op)
            fn = f"test_{cname(namespace)}_{cname(opname)}_reaches_its_route"

            block = [f"static void {fn}(void) {{"]
            if body is None:
                block.append("    mgmt_mount(204, NULL);")
            else:
                block.append(f"    mgmt_mount(200, {c_string(json.dumps(body))});")
            block.append("    axiam_client_t *c = mgmt_signed_in_client();")
            block.append("    axiam_error_t err;")

            args = ["c"]
            frees = []
            for p in params:
                if p["kind"] == "scope":
                    args.append("NULL")
                elif p["kind"] == "path":
                    args.append(f'"{EXAMPLE_UUID}"')
                elif p["kind"] == "query":
                    args.append("NULL")
                elif p["kind"] == "body":
                    bmodel = pascal(op["request_schema"].lstrip("[]"))
                    block.append(f"    {model_type(bmodel)} body;")
