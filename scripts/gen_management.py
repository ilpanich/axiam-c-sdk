def cname(text: str) -> str:
    """A C identifier fragment: lower snake_case, keywords suffixed."""
    ident = snake(pascal(text))
    return f"{ident}_" if ident in C_KEYWORDS else ident


# Type names the HAND-WRITTEN core already owns in the axiam_mgmt_ namespace. A model
# that rendered to one of these would silently redefine it -- which is exactly what
# `Scope` did on the first run, since the spec has a schema by that name and
# management.h had a struct by that name. The generated model keeps the spec's name
# (renaming it would make C the one SDK whose type does not match the contract) and the
# hand-written one carries a qualifier; this list is what makes the NEXT such collision
# a build failure here rather than a confusing redefinition error 4000 lines into a
# generated header.
RESERVED_TYPES = {
    "axiam_mgmt_call_scope_t",
    "axiam_mgmt_page_req_t",
    "axiam_mgmt_error_class_t",
}


def model_type(name: str) -> str:
    """The C typedef name for a model (``Role`` -> ``axiam_mgmt_role_t``)."""
    rendered = f"axiam_mgmt_{snake(pascal(name))}_t"
    if rendered in RESERVED_TYPES:
        raise SystemExit(
            f"schema {name!r} renders to {rendered!r}, which the hand-written core in "
            "include/axiam/management.h already defines. Rename the hand-written type "
            "and add the new name to RESERVED_TYPES -- do NOT rename the model, or C "
            "becomes the one SDK whose type does not match the contract."
        )
    return rendered


def model_prefix(name: str) -> str:
    """The C function prefix for a model (``Role`` -> ``axiam_mgmt_role``)."""
    return f"axiam_mgmt_{snake(pascal(name))}"


def enum_const(model: str, value: str) -> str:
    """A C enum constant (``UserStatus``/``Active`` -> ``AXIAM_MGMT_USER_STATUS_ACTIVE``)."""
    tail = snake(pascal(value)).upper()
    if not tail or not tail[0].isalpha():
        tail = f"V{tail}"
    return f"AXIAM_MGMT_{snake(pascal(model)).upper()}_{tail}"


def comment(text: str, indent: str = "", width: int = 92) -> list[str]:
    """A block comment at ``indent``. C89-style, since this compiles at -std=c11 and below."""
    lines = wrap(escape(text), width - len(indent) - 3)
    if len(lines) == 1:
        return [f"{indent}/* {lines[0]} */"]
    out = [f"{indent}/*"]
    out.extend(f"{indent} * {line}".rstrip() for line in lines)
    out.append(f"{indent} */")
    return out


def doc(text: str, indent: str = "", width: int = 92) -> list[str]:
    """A Doxygen block at ``indent`` -- this repo publishes an API reference from them."""
    paragraphs = [p for p in str(text).split("\n\n") if p.strip()]
    out = [f"{indent}/**"]
    first = True
    for para in paragraphs or [""]:
        if not first:
            out.append(f"{indent} *")
        for line in wrap(escape(para), width - len(indent) - 3):
            out.append(f"{indent} * {line}".rstrip())
        first = False
    out.append(f"{indent} */")
    return out


def c_field(schema: Any, secret: bool = False) -> dict[str, str]:
    """Map a schema to how one struct member is declared, parsed and freed.

    Returns a dict with ``decl`` (the C type), ``kind`` (a tag the emitters switch on)
    and, for references, ``ref`` (the schema name).
    """
    if secret:
        return {"decl": "axiam_sensitive_t *", "kind": "sensitive", "ref": ""}
    if not isinstance(schema, dict):
        return {"decl": "char *", "kind": "json_text", "ref": ""}

    if "$ref" in schema:
        name = pascal(schema["$ref"].split("/")[-1])
        if name in ENUMS:
            return {"decl": f"axiam_mgmt_{snake(name)}_t ", "kind": "enum", "ref": name}
        return {"decl": f"{model_type(name)} *", "kind": "model", "ref": name}

    inner = nullable_ref(schema)
    if inner:
        name = pascal(inner)
        if name in ENUMS:
            return {"decl": f"axiam_mgmt_{snake(name)}_t ", "kind": "enum", "ref": name}
        return {"decl": f"{model_type(name)} *", "kind": "model", "ref": name}

    if isinstance(schema.get("allOf"), list) and len(schema["allOf"]) == 1:
        return c_field(schema["allOf"][0])

    kind = schema.get("type")
    if isinstance(kind, list):
        kind = next((k for k in kind if k != "null"), None)

    if kind == "array":
        item = c_field(schema.get("items") or {})
        if item["kind"] == "string":
            return {"decl": "char **", "kind": "string_array", "ref": ""}
        if item["kind"] == "model":
            return {"decl": f"{model_type(item['ref'])} **", "kind": "model_array",
                    "ref": item["ref"]}
        # Anything else (numbers, nested arrays, free-form objects) is kept as raw JSON
        # rather than given a bespoke C representation nobody would enjoy freeing.
        return {"decl": "char *", "kind": "json_text", "ref": ""}
    if kind == "integer":
        return {"decl": "long ", "kind": "long", "ref": ""}
    if kind == "number":
        return {"decl": "double ", "kind": "double", "ref": ""}
    if kind == "boolean":
        return {"decl": "int ", "kind": "bool", "ref": ""}
    if kind == "string":
        return {"decl": "char *", "kind": "string", "ref": ""}

    return {"decl": "char *", "kind": "json_text", "ref": ""}


def scalar(kind: str) -> bool:
    """True for a member that needs a companion ``has_`` flag when optional.

    A pointer member says "absent" by being NULL. A `long`, `double` or `int` cannot,
    and picking a sentinel (0? -1?) would collide with a value the server can legitimately
    send -- so optional scalars carry an explicit presence flag instead.
    """
    return kind in {"long", "double", "bool", "enum"}


PROJECTION_DOC = (
    "Resolved by the list projection only.\n\n"
    "The server resolves this for a whole page in one query, so it is populated by "
    "`list` and is NULL on `get` (CONTRACT.md \u00a727.11 rule 4). NULL there means \"this "
    "read does not carry it\", not \"there is nothing bound\" -- this SDK does not issue a "
    "second request to fill it in."
)


def projection_map() -> dict[str, list[dict[str, Any]]]:
    """Members a list projection ADDS to its base schema, keyed by the base's name.

    \u00a727.11 rule 4: the server expresses a projection as an ``allOf`` of the named base
    and an anonymous object, so the added property belongs to no schema in
    ``components``. The registry records it as ``response.projected_fields``; this folds
    it back onto the base struct as an OPTIONAL member, which is what makes it NULL on
    the ``get`` that does not project it rather than absent from the type.
    """
    added: dict[str, list[dict[str, Any]]] = {}
    for ns in REGISTRY["namespaces"].values():
        for op in ns["operations"].values():
            response = op.get("response") or {}
            extras = response.get("projected_fields") or []
            base = (response.get("schema") or "").lstrip("[]")
            if not extras or not base:
                continue
            known = {f["name"] for f in added.setdefault(base, [])}
            for extra in extras:
                if extra["name"] not in known:
                    added[base].append(extra)
    return added


PROJECTED: dict[str, list[dict[str, Any]]] = projection_map()


def fields_of(schema_name: str, secrets: set[str]) -> tuple[list[dict[str, Any]], str | None]:
    """Every member of ``schema_name``, in the spec's own order.

    A discriminated union gets two synthetic members instead: the discriminator as a
    string, and the whole object as raw JSON. C has no sum type, and a hand-rolled tagged
    union of five arms would hand the caller a `free()` maze for a shape this SDK only
    ever forwards -- so the tag is what you branch on and the payload stays inspectable.
    """
    schema = SCHEMAS.get(schema_name) or {}
    union = discriminated(schema)
    if union:
        tag, _arms = union
        return ([
            {
                "wire": tag, "name": cname(tag), "decl": "char *", "kind": "string",
                "ref": "", "required": True, "schema": {"type": "string"}, "secret": False,
                "description": f"The `{tag}` discriminator naming which variant this is.",
            },
            {
                "wire": "", "name": "raw", "decl": "char *", "kind": "union_raw",
                "ref": "", "required": False, "schema": {}, "secret": False,
                "description": "The whole object as the server sent it, to read the "
                               "variant's own fields from once `"
                               + tag + "` says which variant it is.",
            },
        ], schema.get("description"))

    props, required, description = flatten(schema_name)
    props = dict(props)
    for extra in PROJECTED.get(schema_name, []):
        if extra["name"] in props:
            continue
        # Never added to `required`: the whole point is that the operation which does NOT
        # project it still parses, with the member NULL (\u00a727.11 rule 4).
        props[extra["name"]] = {
            "type": extra["type"],
            "format": extra.get("format"),
            "description": extra.get("description") or PROJECTION_DOC,
        }
    out: list[dict[str, Any]] = []
    for wire, schema in props.items():
        info = c_field(schema, secret=wire in secrets)
        out.append({
            "wire": wire,
            "name": cname(wire),
            "decl": info["decl"],
            "kind": info["kind"],
            "ref": info["ref"],
            "required": wire in required,
            "schema": schema,
            "secret": wire in secrets,
            "description": schema.get("description") if isinstance(schema, dict) else None,
        })
    return out, description


def field_doc(f: dict[str, Any]) -> str:
    """The one-line description for a member."""
    if f["description"]:
        return escape(f["description"])
    if f["secret"]:
        return f"The server's `{f['wire']}` field -- a ONE-TIME secret (27.5)."
    return f"The server's `{f['wire']}` field."


