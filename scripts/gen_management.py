def op_symbol(namespace: str, opname: str) -> str:
    """The flat C name for one operation.

    `axiam_<namespace>_<operation>`, which is the exact shape CONTRACT.md 27.3's
    per-language table gives C -- its row reads
    `axiam_service_accounts_rotate_secret(client, id, &out)`. The namespace lives in the
    NAME rather than in a receiver, and sorted alphabetically a completion list groups
    exactly the way handles do in the SDKs that have them.

    Deliberately NOT `axiam_mgmt_<ns>_<op>`: an extra segment would be this SDK's own
    invention in the one place 27.3 spells the symbol out. The MODEL types below keep
    the `axiam_mgmt_` prefix, because 27.3 governs the operation accessor and says
    nothing about type names -- and there the prefix earns its keep by separating 145
    generated types from the SDK's own.
    """
    return f"axiam_{cname(namespace)}_{cname(opname)}"


def path_params(op: dict[str, Any]) -> list[str]:
    return re.findall(r"\{([^}]+)\}", op["path"])


def implicit_of(namespace: str, op: dict[str, Any]) -> set[str]:
    """Which path parameters the SDK fills in from the client (27.4 rule 3)."""
    names = set(path_params(op))
    implicit = {"org_id"} & names
    if "tenant_id" in names and namespace in IMPLICIT_TENANT_NAMESPACES:
        implicit.add("tenant_id")
    return implicit


def op_params(namespace: str, op: dict[str, Any]) -> list[dict[str, str]]:
    """The C parameter list for one operation, in declaration order."""
    implicit = implicit_of(namespace, op)
    params: list[dict[str, str]] = []

    if implicit:
        params.append({
            "name": "scope", "decl": "const axiam_mgmt_call_scope_t *", "kind": "scope",
            "wire": "",
            "text": "Per-call `{org_id}`/`{tenant_id}` override, or NULL for the client's "
                    "own (27.4 rule 3).",
        })

    for name in path_params(op):
        if name in implicit:
            continue
        params.append({
            "name": cname(name), "decl": "const char *", "kind": "path", "wire": name,
            "text": f"The `{{{name}}}` path parameter.",
        })

    for q in op["query_params"]:
        # `search` rides on axiam_mgmt_page_req_t with `offset`/`limit` (\u00a727.4 rule 4),
        # not as a separate argument -- otherwise axiam_mgmt_page_next() has no way to
        # carry it past the first request of a walk.
        if op["paginated"] and q["name"] in {"offset", "limit", "search"}:
            continue
        params.append({
            "name": cname(q["name"]), "decl": "const char *", "kind": "query",
            "wire": q["name"],
            "text": f"The `{q['name']}` query parameter"
                    + ("." if q["required"] else ", or NULL to omit it."),
        })

    if op["request_body"] != "none" and op["request_schema"]:
        model = pascal(op["request_schema"].lstrip("[]"))
        params.append({
            "name": "body", "decl": f"const {model_type(model)} *", "kind": "body",
            "wire": "", "text": "The request body.",
        })

    if op["paginated"]:
        params.append({
            "name": "page", "decl": "const axiam_mgmt_page_req_t *", "kind": "page",
            "wire": "", "text": "Which page to fetch, or NULL for the first at the default size.",
        })

    kind = op["response"]["kind"]
    schema = op["response"]["schema"]
    if kind != "none" and schema:
        model = pascal(schema.lstrip("[]"))
        if kind == "page":
            decl = f"axiam_mgmt_{snake(model)}_page_t **"
            text = (f"Receives the page on success; free with "
                    f"axiam_mgmt_{snake(model)}_page_free(). Set to NULL on failure.")
        elif kind == "array":
            decl = f"axiam_mgmt_{snake(model)}_list_t **"
            text = (f"Receives the list on success; free with "
                    f"axiam_mgmt_{snake(model)}_list_free(). Set to NULL on failure.")
        else:
            decl = f"{model_type(model)} **"
            text = (f"Receives the object on success; free with "
                    f"{model_prefix(model)}_free(). Set to NULL on failure.")
        params.append({"name": "out", "decl": decl, "kind": "out", "wire": "", "text": text})

    params.append({
        "name": "err", "decl": "axiam_error_t *", "kind": "err", "wire": "",
        "text": "Filled on failure; may be NULL.",
    })
    return params


def op_signature(namespace: str, opname: str, op: dict[str, Any]) -> str:
    """The full declaration, minus the trailing `;` or ` {`."""
    params = op_params(namespace, op)
    args = ["axiam_client_t *c"] + [f"{p['decl']}{p['name']}" for p in params]
    return f"axiam_error_kind_t {op_symbol(namespace, opname)}({', '.join(args)})"


def op_doc(namespace: str, opname: str, op: dict[str, Any]) -> str:
    """The Doxygen summary for one operation."""
    entry = (SPEC.get("paths") or {}).get(op["path"]) or {}
    node = entry.get(op["method"].lower()) or {}
    described = node.get("summary") or node.get("description")

    lead = f"`{op['method']} {op['path']}`."
    if described:
        lead = f"{escape(described)}\n\n`{op['method']} {op['path']}`."

    kind = op["response"]["kind"]
    if kind == "page":
        lead += ("\n\nReturns ONE page. `total` on it is the server's count across all "
                 "pages and is not `count` -- see 27.4 rule 4.")
    elif kind == "array":
        lead += ("\n\nReturns the server's complete list. This endpoint is NOT paginated, "
                 "so the result is a plain list and never a page (27.4 rule 4).")
    elif kind == "none":
        lead += "\n\nReturns nothing; the server answers with an empty body."

    if op["method"] == "DELETE":
        lead += ("\n\nNOT idempotent (27.4 rule 6): deleting something already deleted "
                 "fails with AXIAM_MGMT_ERR_NOT_FOUND rather than succeeding quietly.")
    if op["sensitive_response_fields"]:
        fields = ", ".join(f"`{f}`" for f in op["sensitive_response_fields"])
        lead += (f"\n\nThe response carries a ONE-TIME secret ({fields}): the server will "
                 "not return it again, so a caller that does not persist it here cannot "
                 "recover it (27.5).")
    return lead


