def emit_parse_field(f: dict[str, Any], indent: str = "    ") -> list[str]:
    """Parse one member out of `src` into `out->name`."""
    w, n, kind = f["wire"], f["name"], f["kind"]
    o = []
    if kind == "union_raw":
        o.append(f"{indent}out->{n} = cJSON_PrintUnformatted(src);")
        return o

    o.append(f'{indent}item = cJSON_GetObjectItemCaseSensitive(src, "{w}");')

    if kind == "string":
        o.append(f"{indent}if (cJSON_IsString(item)) out->{n} = axiam_strdup0(item->valuestring);")
    elif kind == "sensitive":
        # 27.5: a one-time secret goes behind Sensitive the moment it is parsed, so it
        # cannot reach a log line by way of an ordinary struct member.
        o.append(f"{indent}if (cJSON_IsString(item)) out->{n} = axiam_sensitive_new(item->valuestring);")
    elif kind in {"long", "double"}:
        cast = "(long)" if kind == "long" else "(double)"
        o.append(f"{indent}if (cJSON_IsNumber(item)) {{ out->{n} = {cast} item->valuedouble;")
        if not f["required"]:
            o.append(f"{indent}    out->has_{n} = 1; }}")
        else:
            o.append(f"{indent}}}")
    elif kind == "bool":
        o.append(f"{indent}if (cJSON_IsBool(item)) {{ out->{n} = cJSON_IsTrue(item) ? 1 : 0;")
        if not f["required"]:
            o.append(f"{indent}    out->has_{n} = 1; }}")
        else:
            o.append(f"{indent}}}")
    elif kind == "enum":
        fn = f"axiam_mgmt_{snake(f['ref'])}_from_wire"
        o.append(f"{indent}if (cJSON_IsString(item) && {fn}(item->valuestring, &out->{n}) == 0) {{")
        if not f["required"]:
            o.append(f"{indent}    out->has_{n} = 1;")
        else:
            o.append(f"{indent}    (void) 0;")
        o.append(f"{indent}}}")
    elif kind == "model":
        o.append(f"{indent}if (cJSON_IsObject(item)) out->{n} = {model_prefix(f['ref'])}_parse(item);")
    elif kind == "json_text":
        o.append(f"{indent}if (item) out->{n} = cJSON_PrintUnformatted(item);")
    elif kind == "string_array":
        o.append(f"{indent}if (cJSON_IsArray(item)) {{")
        o.append(f"{indent}    size_t n = (size_t) cJSON_GetArraySize(item);")
        o.append(f"{indent}    if (n > 0) {{")
        o.append(f"{indent}        out->{n} = (char **) calloc(n, sizeof(char *));")
        o.append(f"{indent}        if (!out->{n}) {{ {model_prefix(f['owner'])}_free(out); return NULL; }}")
        o.append(f"{indent}        for (size_t i = 0; i < n; i++) {{")
        o.append(f"{indent}            const cJSON *e = cJSON_GetArrayItem(item, (int) i);")
        o.append(f"{indent}            if (cJSON_IsString(e)) out->{n}[i] = axiam_strdup0(e->valuestring);")
        o.append(f"{indent}        }}")
        o.append(f"{indent}        out->{n}_count = n;")
        o.append(f"{indent}    }}")
        o.append(f"{indent}}}")
    elif kind == "model_array":
        t = model_type(f["ref"])
        o.append(f"{indent}if (cJSON_IsArray(item)) {{")
        o.append(f"{indent}    size_t n = (size_t) cJSON_GetArraySize(item);")
        o.append(f"{indent}    if (n > 0) {{")
        o.append(f"{indent}        out->{n} = ({t} **) calloc(n, sizeof({t} *));")
        o.append(f"{indent}        if (!out->{n}) {{ {model_prefix(f['owner'])}_free(out); return NULL; }}")
        o.append(f"{indent}        for (size_t i = 0; i < n; i++) {{")
        o.append(f"{indent}            const cJSON *e = cJSON_GetArrayItem(item, (int) i);")
        o.append(f"{indent}            if (cJSON_IsObject(e)) out->{n}[i] = {model_prefix(f['ref'])}_parse(e);")
        o.append(f"{indent}        }}")
        o.append(f"{indent}        out->{n}_count = n;")
        o.append(f"{indent}    }}")
        o.append(f"{indent}}}")
    return o


def emit_free_field(f: dict[str, Any], indent: str = "    ") -> list[str]:
    """Release one member."""
    n, kind = f["name"], f["kind"]
    if kind == "string":
        return [f"{indent}free(value->{n});"]
    if kind == "sensitive":
        return [f"{indent}axiam_sensitive_free(value->{n});"]
    if kind == "model":
        return [f"{indent}{model_prefix(f['ref'])}_free(value->{n});"]
    if kind in {"json_text", "union_raw"}:
        return [f"{indent}free(value->{n});"]
    if kind == "string_array":
        return [
            f"{indent}if (value->{n}) {{",
            f"{indent}    for (size_t i = 0; i < value->{n}_count; i++) free(value->{n}[i]);",
            f"{indent}    free(value->{n});",
            f"{indent}}}",
        ]
    if kind == "model_array":
        return [
            f"{indent}if (value->{n}) {{",
            f"{indent}    for (size_t i = 0; i < value->{n}_count; i++) "
            f"{model_prefix(f['ref'])}_free(value->{n}[i]);",
            f"{indent}    free(value->{n});",
            f"{indent}}}",
        ]
    return []


def emit_build_field(f: dict[str, Any], indent: str = "    ") -> list[str]:
    """Serialize one member into the request body, honouring 27.4 rule 5."""
    w, n, kind = f["wire"], f["name"], f["kind"]
    o = []
    if kind in {"string", "model", "json_text", "string_array", "model_array"}:
        guard = f"if (value->{n})"
    elif kind == "sensitive":
        guard = f"if (value->{n})"
    elif f["required"]:
        guard = "if (1)"
    else:
        guard = f"if (value->has_{n})"

    if kind == "union_raw":
        return []

    o.append(f"{indent}{guard} {{")
    body = indent + "    "
    if kind == "string":
        o.append(f'{body}cJSON_AddStringToObject(obj, "{w}", value->{n});')
    elif kind == "sensitive":
        # 27.5: this is the one place a secret is revealed, on the way to the wire.
        o.append(f'{body}cJSON_AddStringToObject(obj, "{w}", axiam_sensitive_reveal(value->{n}));')
    elif kind == "long":
        o.append(f'{body}cJSON_AddNumberToObject(obj, "{w}", (double) value->{n});')
    elif kind == "double":
        o.append(f'{body}cJSON_AddNumberToObject(obj, "{w}", value->{n});')
    elif kind == "bool":
        o.append(f'{body}cJSON_AddBoolToObject(obj, "{w}", value->{n});')
    elif kind == "enum":
        fn = f"axiam_mgmt_{snake(f['ref'])}_to_wire"
        o.append(f'{body}cJSON_AddStringToObject(obj, "{w}", {fn}(value->{n}));')
    elif kind == "model":
        o.append(f"{body}cJSON *sub = {model_prefix(f['ref'])}_build(value->{n});")
        o.append(f'{body}if (sub) cJSON_AddItemToObject(obj, "{w}", sub);')
    elif kind == "json_text":
        o.append(f"{body}cJSON *sub = cJSON_Parse(value->{n});")
        o.append(f'{body}if (sub) cJSON_AddItemToObject(obj, "{w}", sub);')
    elif kind == "string_array":
        o.append(f'{body}cJSON *arr = cJSON_AddArrayToObject(obj, "{w}");')
        o.append(f"{body}for (size_t i = 0; arr && i < value->{n}_count; i++)")
        o.append(f"{body}    cJSON_AddItemToArray(arr, cJSON_CreateString(value->{n}[i]));")
    elif kind == "model_array":
        o.append(f'{body}cJSON *arr = cJSON_AddArrayToObject(obj, "{w}");')
        o.append(f"{body}for (size_t i = 0; arr && i < value->{n}_count; i++) {{")
        o.append(f"{body}    cJSON *sub = {model_prefix(f['ref'])}_build(value->{n}[i]);")
        o.append(f"{body}    if (sub) cJSON_AddItemToArray(arr, sub);")
        o.append(f"{body}}}")
    o.append(f"{indent}}}")
    return o


def emit_models_source() -> str:
    """parse / free / build for every model, plus the page and list wrappers."""
    secrets = sensitive_map()
    out = [BANNER_C]
    out.append("")
    out.append("#include <stdlib.h>")
    out.append("#include <string.h>")
    out.append("")
    out.append('#include "axiam/management_models.h"')
    out.append('#include "internal.h"')
    out.append('#include "management_internal.h"')
    out.append("")

    # ---- enum conversions ----
    for name in schema_closure():
        rendered = pascal(name)
        if rendered not in ENUMS:
            continue
        values = [str(v) for v in ((SCHEMAS.get(name) or {}).get("enum") or [])]
        if not values:
            continue
        s = snake(rendered)
        out.append(f"int axiam_mgmt_{s}_from_wire(const char *value, axiam_mgmt_{s}_t *out) {{")
        out.append("    if (!value || !out) return -1;")
        for v in values:
            out.append(f'    if (strcmp(value, "{v}") == 0) {{ *out = {enum_const(rendered, v)}; return 0; }}')
        out.extend(comment(
            "\u00a727.11 rule 1: an unrecognised value decodes, it does not fail. Reporting it "
            "here would make the caller drop the whole record over one field it did not "
            "ask about. It is still never read as one of the KNOWN constants -- that "
            "would turn a new server state into a wrong one, and on this surface these "
            "values gate access.",
            "    "))
        out.append(f"    *out = {enum_const(rendered, 'unknown')};")
        out.append("    return 0;")
        out.append("}")
        out.append("")
        out.append(f"const char *axiam_mgmt_{s}_to_wire(axiam_mgmt_{s}_t value) {{")
        out.append("    switch (value) {")
        for v in values:
            out.append(f'        case {enum_const(rendered, v)}: return "{v}";')
        out.extend(comment(
            "The empty string, which no server value is: an unrecognised value carried "
            "back into an update is refused by the server rather than written as a "
            "spelling it never used.", "        "))
        out.append(f'        case {enum_const(rendered, "unknown")}: return "";')
        out.append("    }")
        out.append(f'    return "{values[0]}";')
        out.append("}")
        out.append("")

    # ---- forward declarations for parse/build ----
    modelled = []
    for name in schema_closure():
        rendered = pascal(name)
        if rendered in ENUMS:
            continue
        fields, _ = fields_of(name, secrets.get(name, set()))
        if fields:
            modelled.append((name, rendered, fields))

    out.extend(comment("Internal parse/build, declared up front because models are mutually recursive."))
    for _, rendered, _ in modelled:
        out.append(f"{model_type(rendered)} *{model_prefix(rendered)}_parse(const cJSON *src);")
        out.append(f"cJSON *{model_prefix(rendered)}_build(const {model_type(rendered)} *value);")
    out.append("")

    for name, rendered, fields in modelled:
        for f in fields:
            f["owner"] = rendered

        # free
        out.append(f"void {model_prefix(rendered)}_free({model_type(rendered)} *value) {{")
        out.append("    if (!value) return;")
        for f in fields:
            out.extend(emit_free_field(f))
        out.append("    free(value);")
        out.append("}")
        out.append("")

        # parse
        out.append(f"{model_type(rendered)} *{model_prefix(rendered)}_parse(const cJSON *src) {{")
        out.append("    if (!cJSON_IsObject(src)) return NULL;")
        out.append(f"    {model_type(rendered)} *out = ({model_type(rendered)} *) "
                   f"calloc(1, sizeof(*out));")
        out.append("    if (!out) return NULL;")
        out.append("    const cJSON *item;")
        out.append("    (void) item;")
        for f in fields:
            out.extend(emit_parse_field(f))
        out.append("    return out;")
        out.append("}")
        out.append("")

        # build
        out.append(f"cJSON *{model_prefix(rendered)}_build(const {model_type(rendered)} *value) {{")
        out.append("    if (!value) return NULL;")
        if any(f["kind"] == "union_raw" for f in fields):
            out.extend(comment(
                "A union is forwarded EXACTLY as received. Re-encoding from the two "
                "members this SDK models would drop every field belonging to the variant "
                "it does not model -- and the server round-trips those.", "    "))
            out.append("    if (value->raw) return cJSON_Parse(value->raw);")
        out.append("    cJSON *obj = cJSON_CreateObject();")
        out.append("    if (!obj) return NULL;")
        for f in fields:
            out.extend(emit_build_field(f))
        out.append("    return obj;")
        out.append("}")
        out.append("")

    # ---- page / list frees ----
    for name in paginated_models():
        s = snake(name)
        out.append(f"void axiam_mgmt_{s}_page_free(axiam_mgmt_{s}_page_t *page) {{")
        out.append("    if (!page) return;")
        out.append("    if (page->items) {")
        out.append(f"        for (size_t i = 0; i < page->count; i++) {model_prefix(name)}_free(page->items[i]);")
        out.append("        free(page->items);")
        out.append("    }")
        out.append("    free(page);")
        out.append("}")
        out.append("")

    for name in array_models():
        s = snake(name)
        out.append(f"void axiam_mgmt_{s}_list_free(axiam_mgmt_{s}_list_t *list) {{")
        out.append("    if (!list) return;")
        out.append("    if (list->items) {")
        out.append(f"        for (size_t i = 0; i < list->count; i++) {model_prefix(name)}_free(list->items[i]);")
        out.append("        free(list->items);")
        out.append("    }")
        out.append("    free(list);")
        out.append("}")
        out.append("")

    return "\n".join(out) + "\n"


