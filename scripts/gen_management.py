def emit_ops_source() -> str:
    """The 146 operation bodies. Every one funnels through axiam_mgmt_send() (27.8)."""
    out = [BANNER_C, ""]
    out.append("#include <stdlib.h>")
    out.append("#include <string.h>")
    out.append("")
    out.append('#include "axiam/management_ops.h"')
    out.append('#include "internal.h"')
    out.append('#include "management_internal.h"')
    out.append("")
    out.extend(comment(
        "Internal parse/build, shared with management_models.c. Declared rather than "
        "made public: a caller has the typed operations above and never needs to hand a "
        "raw cJSON to a model."))
    secrets = sensitive_map()
    modelled = []
    for name in schema_closure():
        rendered = pascal(name)
        if rendered in ENUMS:
            continue
        if fields_of(name, secrets.get(name, set()))[0]:
            modelled.append(rendered)
    for rendered in modelled:
        out.append(f"{model_type(rendered)} *{model_prefix(rendered)}_parse(const cJSON *src);")
        out.append(f"cJSON *{model_prefix(rendered)}_build(const {model_type(rendered)} *value);")
    out.append("")

    for namespace, nsdef in REGISTRY["namespaces"].items():
        for opname, op in nsdef["operations"].items():
            out.extend(emit_op_body(namespace, opname, op))
            out.append("")

    return "\n".join(out) + "\n"


def emit_op_body(namespace: str, opname: str, op: dict[str, Any]) -> list[str]:
    """One operation implementation."""
    params = op_params(namespace, op)
    implicit = implicit_of(namespace, op)
    canonical = f"{namespace}.{opname}"
    kind = op["response"]["kind"]
    schema = op["response"]["schema"]
    model = pascal(schema.lstrip("[]")) if schema else ""

    out = [op_signature(namespace, opname, op) + " {"]
    has_out = any(p["kind"] == "out" for p in params)
    if has_out:
        out.append("    if (out) *out = NULL;")

    # ---- path ----
    names = path_params(op)
    if names:
        out.append(f"    const char *path_names[{len(names)}];")
        out.append(f"    const char *path_values[{len(names)}];")
        for i, name in enumerate(names):
            out.append(f'    path_names[{i}] = "{name}";')
            if name == "org_id" and name in implicit:
                out.append(f"    path_values[{i}] = axiam_mgmt_resolved_org_id(c, scope);")
            elif name == "tenant_id" and name in implicit:
                out.append(f"    path_values[{i}] = axiam_mgmt_resolved_tenant_id(c, scope);")
            else:
                out.append(f"    path_values[{i}] = {cname(name)};")
        out.append(f'    char *path = axiam_mgmt_path("{op["path"]}", path_names, path_values, {len(names)});')
    else:
        out.append(f'    char *path = axiam_mgmt_path("{op["path"]}", NULL, NULL, 0);')

    out.append("    if (!path) {")
    if implicit:
        out.extend(comment(
            "A NULL path means an identifier was missing -- almost always the implicit "
            "org/tenant id on a client that was never given one. Reporting it names what "
            "to fix; sending an empty path segment would surface as an undiagnosable 404.",
            "        "))
        out.append(f'        axiam_error_set(err, AXIAM_ERR_NETWORK, 0, "{canonical}: '
                   f'missing an organization or tenant id -- configure one on the client '
                   f'or pass a scope (27.4 rule 3)");')
    else:
        out.append(f'        axiam_error_set(err, AXIAM_ERR_NETWORK, 0, "{canonical}: '
                   f'could not build the request path");')
    out.append("        return AXIAM_ERR_NETWORK;")
    out.append("    }")

    # ---- query ----
    queries = [p for p in params if p["kind"] == "query"]
    if op["paginated"] or queries:
        count = len(queries) + (3 if op["paginated"] else 0)
        out.append(f"    const char *q_names[{count}];")
        out.append(f"    const char *q_values[{count}];")
        idx = 0
        if op["paginated"]:
            out.append("    char offset_buf[24], limit_buf[24];")
            out.append("    axiam_mgmt_page_query(page, offset_buf, limit_buf);")
            out.append(f'    q_names[{idx}] = "offset"; q_values[{idx}] = offset_buf;')
            idx += 1
            out.append(f'    q_names[{idx}] = "limit"; q_values[{idx}] = limit_buf;')
            idx += 1
            # A NULL value is OMITTED by axiam_mgmt_query, which is what makes an unset
            # or blank term send no `search` key at all (§27.4 rule 4).
            out.append(f'    q_names[{idx}] = "search";')
            out.append(f'    q_values[{idx}] = page ? axiam_mgmt_page_search(page->search) : NULL;')
            idx += 1
        for p in queries:
            out.append(f'    q_names[{idx}] = "{p["wire"]}"; q_values[{idx}] = {p["name"]};')
            idx += 1
        out.append(f"    path = axiam_mgmt_query(path, q_names, q_values, {count});")
        out.append("    if (!path) {")
        out.append(f'        axiam_error_set(err, AXIAM_ERR_NETWORK, 0, "{canonical}: out of memory");')
        out.append("        return AXIAM_ERR_NETWORK;")
        out.append("    }")

    # ---- body ----
    body_param = next((p for p in params if p["kind"] == "body"), None)
    if body_param:
        bmodel = pascal(op["request_schema"].lstrip("[]"))
        out.append(f"    char *body_json = axiam_mgmt_render({model_prefix(bmodel)}_build(body));")
    else:
        out.append("    char *body_json = NULL;")

    # ---- send ----
    out.append("    cJSON *json = NULL;")
    out.append("    axiam_error_kind_t rc = axiam_mgmt_send(")
    out.append(f'        c, "{canonical}", "{op["method"]}", "{op["path"]}", path, body_json,')
    out.append("        &json, err);")
    out.append("    free(path);")
    out.append("    free(body_json);")
    out.append("    if (rc != AXIAM_OK) return rc;")

    # ---- decode ----
    if kind == "none" or not schema:
        out.append("    cJSON_Delete(json);")
        out.append("    return AXIAM_OK;")
    elif kind == "page":
        s = snake(model)
        out.append(f"    axiam_mgmt_{s}_page_t *result = (axiam_mgmt_{s}_page_t *) calloc(1, sizeof(*result));")
        out.append("    if (!result) { cJSON_Delete(json); return AXIAM_ERR_NETWORK; }")
        out.append("    const cJSON *items = axiam_mgmt_page_items(json);")
        out.append("    size_t n = items ? (size_t) cJSON_GetArraySize(items) : 0;")
        out.append("    if (n > 0) {")
        out.append(f"        result->items = ({model_type(model)} **) calloc(n, sizeof({model_type(model)} *));")
        out.append(f"        if (!result->items) {{ axiam_mgmt_{s}_page_free(result); cJSON_Delete(json); return AXIAM_ERR_NETWORK; }}")
        out.append("        for (size_t i = 0; i < n; i++)")
        out.append(f"            result->items[i] = {model_prefix(model)}_parse(cJSON_GetArrayItem((cJSON *) items, (int) i));")
        out.append("        result->count = n;")
        out.append("    }")
        out.append("    result->total = axiam_mgmt_page_total(json, (long) n);")
        out.append("    result->request = page ? *page : (axiam_mgmt_page_req_t) { 0, AXIAM_MGMT_DEFAULT_LIMIT, NULL };")
        out.append("    cJSON_Delete(json);")
        out.append("    if (out) *out = result;")
        out.append(f"    else axiam_mgmt_{s}_page_free(result);")
        out.append("    return AXIAM_OK;")
    elif kind == "array":
        s = snake(model)
        out.append(f"    axiam_mgmt_{s}_list_t *result = (axiam_mgmt_{s}_list_t *) calloc(1, sizeof(*result));")
        out.append("    if (!result) { cJSON_Delete(json); return AXIAM_ERR_NETWORK; }")
        out.append("    size_t n = cJSON_IsArray(json) ? (size_t) cJSON_GetArraySize(json) : 0;")
        out.append("    if (n > 0) {")
        out.append(f"        result->items = ({model_type(model)} **) calloc(n, sizeof({model_type(model)} *));")
        out.append(f"        if (!result->items) {{ axiam_mgmt_{s}_list_free(result); cJSON_Delete(json); return AXIAM_ERR_NETWORK; }}")
        out.append("        for (size_t i = 0; i < n; i++)")
        out.append(f"            result->items[i] = {model_prefix(model)}_parse(cJSON_GetArrayItem(json, (int) i));")
        out.append("        result->count = n;")
        out.append("    }")
        out.append("    cJSON_Delete(json);")
        out.append("    if (out) *out = result;")
        out.append(f"    else axiam_mgmt_{s}_list_free(result);")
        out.append("    return AXIAM_OK;")
    else:
        out.append(f"    {model_type(model)} *result = {model_prefix(model)}_parse(json);")
        out.append("    cJSON_Delete(json);")
        out.append("    if (!result) {")
        out.append(f'        axiam_error_set(err, AXIAM_ERR_NETWORK, 0, "{canonical}: '
                   f'the response body was not the expected object");')
        out.append("        return AXIAM_ERR_NETWORK;")
        out.append("    }")
        out.append("    if (out) *out = result;")
        out.append(f"    else {model_prefix(model)}_free(result);")
        out.append("    return AXIAM_OK;")

    out.append("}")
    return out


